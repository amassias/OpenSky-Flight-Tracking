"""Regenerate src/airlineCodes.ts from data/Airlines data (OpenFlights format).

Keeps active airlines with both a two-character IATA designator and a
three-letter ICAO code, so the search can read a ticket flight number
(AF1234) as the callsign aircraft transmit (AFR1234).
"""

import csv
import json
import os
import re
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
codes = defaultdict(list)
with open(os.path.join(ROOT, "data", "Airlines data"), encoding="utf-8") as source:
    for row in csv.reader(source):
        if len(row) < 8:
            continue
        iata, icao, active = row[3].strip(), row[4].strip(), row[7].strip()
        if active == "Y" and re.fullmatch(r"[A-Z0-9]{2}", iata) and re.fullmatch(r"[A-Z]{3}", icao) and icao not in codes[iata]:
            codes[iata].append(icao)

table = json.dumps(dict(sorted(codes.items())), separators=(",", ":"))
with open(os.path.join(ROOT, "src", "airlineCodes.ts"), "w", encoding="utf-8") as target:
    target.write("// Generated by scripts/build_airline_codes.py from data/Airlines data. Do not edit.\n")
    target.write("/** IATA airline designator to the ICAO codes used in callsigns. */\n")
    target.write(f"export const AIRLINE_ICAO_BY_IATA: Readonly<Record<string, readonly string[]>> = {table};\n")
