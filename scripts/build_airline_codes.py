"""Regenerate src/shared/airlineCodes.ts from data/Airlines data (OpenFlights format).

Keeps active airlines with both a two-character IATA designator and a
three-letter ICAO code, so the search can read a ticket flight number
(AF1234) as the callsign aircraft transmit (AFR1234).
"""

import argparse
import csv
import json
import os
import re
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
codes = defaultdict(list)
with open(os.path.join(ROOT, "data", "Airlines data"), encoding="utf-8") as source:
    for row in csv.reader(source):
        if len(row) < 8:
            continue
        iata, icao, active = row[3].strip(), row[4].strip(), row[7].strip()
        if active == "Y" and re.fullmatch(r"[A-Z0-9]{2}", iata) and re.fullmatch(r"[A-Z]{3}", icao) and icao not in codes[iata]:
            codes[iata].append(icao)

# Current, sourced assignments take precedence over the historic OpenFlights table.
with open(os.path.join(ROOT, "data", "airline-code-corrections.json"), encoding="utf-8") as source:
    corrections = json.load(source)
for correction in corrections:
    iata, operators = correction["iata"], correction["icao"]
    if not re.fullmatch(r"[A-Z0-9]{2}", iata) or not operators or any(not re.fullmatch(r"[A-Z]{3}", code) for code in operators):
        raise ValueError(f"Invalid airline correction: {iata}")
    if not correction.get("sources") or not correction.get("checked_at"):
        raise ValueError(f"Unsourced airline correction: {iata}")
    # Prevent reverse ticket-number lookup retaining an old designator (e.g. 9S/CQH).
    for old_iata in list(codes):
        codes[old_iata] = [code for code in codes[old_iata] if code not in operators]
        if not codes[old_iata]:
            del codes[old_iata]
    codes[iata] = operators

table = json.dumps(dict(sorted(codes.items())), separators=(",", ":"))
output = ("// Generated by scripts/build_airline_codes.py from OpenFlights and sourced corrections. Do not edit.\n"
          "/** IATA airline designator to the ICAO codes used in callsigns. */\n"
          f"export const AIRLINE_ICAO_BY_IATA: Readonly<Record<string, readonly string[]>> = {table};\n")
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Verify the committed table without writing it")
args = parser.parse_args()
path = os.path.join(ROOT, "src", "shared", "airlineCodes.ts")
if args.check:
    with open(path, encoding="utf-8") as target:
        if target.read() != output:
            raise SystemExit("Airline codes are stale; run python3 scripts/build_airline_codes.py")
else:
    with open(path, "w", encoding="utf-8") as target:
        target.write(output)
